-- The lab schema: a small, editable copy of real data for the dashboard's
-- Data editor and the "Lab" target of the SQL console (DATA_EDITOR_PLAN.md).
--
-- Run by backend/lab.py as role cc_lab, inside one transaction, right after
-- `DROP SCHEMA lab CASCADE; CREATE SCHEMA lab AUTHORIZATION cc_lab`. cc_lab
-- can read cc but write only here, so nothing done in the lab reaches the
-- loaded releases. {edges} is replaced by the number of strongest
-- connections per dataset whose neurons are copied.
SET LOCAL search_path = lab, cc, public;

CREATE TABLE dataset (
    dataset_id  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    name        text NOT NULL CHECK (name <> ''),
    organism    text
);

CREATE TABLE release (
    release_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id     smallint NOT NULL REFERENCES dataset ON DELETE RESTRICT,
    version_label  text NOT NULL CHECK (version_label <> ''),
    release_order  integer NOT NULL CHECK (release_order > 0),
    UNIQUE (dataset_id, version_label),
    UNIQUE (dataset_id, release_order),
    UNIQUE (release_id, dataset_id)             -- target of composite FKs
);

CREATE TABLE neuron (
    neuron_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id        smallint NOT NULL REFERENCES dataset ON DELETE RESTRICT,
    source_neuron_id  text NOT NULL CHECK (source_neuron_id <> ''),
    cell_type         text,
    side              text CHECK (side IN ('L', 'R', 'center')),
    primary_region    text,
    UNIQUE (dataset_id, source_neuron_id),
    UNIQUE (neuron_id, dataset_id)              -- target of composite FKs
);
CREATE INDEX neuron_cell_type_idx ON neuron (cell_type);

-- Both endpoints and the release must belong to the connection's dataset.
CREATE TABLE connection (
    release_id      integer NOT NULL,
    dataset_id      smallint NOT NULL,
    pre_neuron_id   bigint NOT NULL,
    post_neuron_id  bigint NOT NULL,
    synapse_count   integer NOT NULL CHECK (synapse_count > 0),
    PRIMARY KEY (release_id, pre_neuron_id, post_neuron_id),
    FOREIGN KEY (release_id, dataset_id) REFERENCES release (release_id, dataset_id) ON DELETE CASCADE,
    FOREIGN KEY (pre_neuron_id, dataset_id) REFERENCES neuron (neuron_id, dataset_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (post_neuron_id, dataset_id) REFERENCES neuron (neuron_id, dataset_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX connection_post_idx ON connection (post_neuron_id);

CREATE VIEW neuron_degree AS
SELECT r.release_id, r.version_label, n.neuron_id, n.source_neuron_id, n.cell_type,
       (SELECT count(*) FROM connection c WHERE c.release_id = r.release_id AND c.pre_neuron_id = n.neuron_id) AS out_partners,
       (SELECT coalesce(sum(c.synapse_count), 0) FROM connection c
         WHERE c.release_id = r.release_id AND c.pre_neuron_id = n.neuron_id) AS out_synapses,
       (SELECT count(*) FROM connection c WHERE c.release_id = r.release_id AND c.post_neuron_id = n.neuron_id) AS in_partners,
       (SELECT coalesce(sum(c.synapse_count), 0) FROM connection c
         WHERE c.release_id = r.release_id AND c.post_neuron_id = n.neuron_id) AS in_synapses
FROM neuron n JOIN release r USING (dataset_id);

-- ------------------------------------------------- copy of the real subset
INSERT INTO dataset (dataset_id, code, name, organism)
SELECT dataset_id, code, name, organism FROM cc.dataset;

INSERT INTO release (release_id, dataset_id, version_label, release_order)
SELECT release_id, dataset_id, version_label, release_order FROM cc.release WHERE ingestion_status = 'loaded';

-- Neurons of the strongest connections that are current in each dataset's
-- latest release (served by the partial index connection_dataset_open_idx).
CREATE TEMP TABLE lab_pick ON COMMIT DROP AS
SELECT DISTINCT t.dataset_id, v.neuron_id
FROM cc.dataset d
CROSS JOIN LATERAL (
    SELECT c.dataset_id, c.pre_neuron_id, c.post_neuron_id
    FROM cc.connection c
    WHERE c.dataset_id = d.dataset_id AND upper_inf(c.tx) AND upper_inf(c.valid_rel) AND c.synapse_count > 0
    ORDER BY c.synapse_count DESC, c.connection_id
    LIMIT {edges}) t
CROSS JOIN LATERAL (VALUES (t.pre_neuron_id), (t.post_neuron_id)) v(neuron_id);

INSERT INTO neuron (neuron_id, dataset_id, source_neuron_id, cell_type, side, primary_region)
SELECT dn.dataset_neuron_id, dn.dataset_id, dn.source_neuron_id,
       (SELECT a.annotation_value FROM cc.annotation a
         WHERE a.dataset_neuron_id = dn.dataset_neuron_id AND a.annotation_key = 'cell_type' AND upper_inf(a.tx)
         ORDER BY upper(a.valid_rel) DESC NULLS FIRST LIMIT 1),
       (SELECT CASE lower(a.annotation_value) WHEN 'left' THEN 'L' WHEN 'l' THEN 'L'
                    WHEN 'right' THEN 'R' WHEN 'r' THEN 'R' WHEN 'center' THEN 'center' END
          FROM cc.annotation a
         WHERE a.dataset_neuron_id = dn.dataset_neuron_id AND a.annotation_key = 'side' AND upper_inf(a.tx)
         ORDER BY upper(a.valid_rel) DESC NULLS FIRST LIMIT 1),
       (SELECT b.code FROM cc.neuron_primary_region p JOIN cc.brain_region_label b USING (brain_region_id)
         WHERE p.dataset_neuron_id = dn.dataset_neuron_id
         ORDER BY p.release_id DESC LIMIT 1)
FROM lab_pick p JOIN cc.dataset_neuron dn ON dn.dataset_neuron_id = p.neuron_id;

-- Their connections to each other, as currently recorded, in every release.
INSERT INTO connection (release_id, dataset_id, pre_neuron_id, post_neuron_id, synapse_count)
SELECT r.release_id, c.dataset_id, c.pre_neuron_id, c.post_neuron_id, c.synapse_count
FROM neuron a
JOIN cc.connection c ON c.pre_neuron_id = a.neuron_id
JOIN neuron b ON b.neuron_id = c.post_neuron_id
JOIN release r ON r.dataset_id = c.dataset_id AND c.valid_rel @> r.release_order
WHERE upper_inf(c.tx) AND c.synapse_count > 0;

-- new rows continue after the copied ids
SELECT setval(pg_get_serial_sequence('lab.dataset', 'dataset_id'), coalesce(max(dataset_id), 0) + 1, false) FROM dataset;
SELECT setval(pg_get_serial_sequence('lab.release', 'release_id'), coalesce(max(release_id), 0) + 1, false) FROM release;
SELECT setval(pg_get_serial_sequence('lab.neuron', 'neuron_id'), coalesce(max(neuron_id), 0) + 1, false) FROM neuron;

-- ------------------------------------------------- audit trail of changes
-- Installed after the copy, so it records only what is done in the lab.
CREATE TABLE change_log (
    change_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    changed_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    changed_by  text NOT NULL DEFAULT current_user,
    table_name  text NOT NULL,
    operation   text NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    old_row     jsonb,
    new_row     jsonb
);

CREATE FUNCTION log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO lab.change_log (table_name, operation, old_row, new_row)
    VALUES (TG_TABLE_NAME, TG_OP,
            CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END,
            CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END);
    RETURN NULL;
END $$;

CREATE TRIGGER dataset_log AFTER INSERT OR UPDATE OR DELETE ON dataset
    FOR EACH ROW EXECUTE FUNCTION log_change();
CREATE TRIGGER release_log AFTER INSERT OR UPDATE OR DELETE ON release
    FOR EACH ROW EXECUTE FUNCTION log_change();
CREATE TRIGGER neuron_log AFTER INSERT OR UPDATE OR DELETE ON neuron
    FOR EACH ROW EXECUTE FUNCTION log_change();
CREATE TRIGGER connection_log AFTER INSERT OR UPDATE OR DELETE ON connection
    FOR EACH ROW EXECUTE FUNCTION log_change();

COMMENT ON SCHEMA lab IS 'Editable copy of a real-data subset; rebuilt by "Reset lab". Changes here never reach schema cc.';
